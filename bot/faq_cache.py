_STOP_WORDS = {
    "а", "в", "и", "к", "на", "не", "но", "о", "от", "по", "с", "у",
    "я", "вы", "мы", "он", "она", "оно", "они", "это", "то",
    "как", "что", "где", "когда", "кто", "чем", "ли",
    "есть", "будет", "можно", "нужно", "нет", "да",
}

def _normalize(text: str) -> str:
    text = text.lower()
    text = re.sub(r"[^а-яёa-z0-9\s]", " ", text)
    tokens = [t for t in text.split() if t and t not in _STOP_WORDS]
    return " ".join(tokens)

def _tokens(text: str) -> set[str]:
    return set(_normalize(text).split())

_NORM_TO_ANSWER: dict[str, str] = {}
_TOKEN_INDEX: list[tuple[set[str], str]] = []

for _q, _a in FAQ.items():
    _norm = _normalize(_q)
    _NORM_TO_ANSWER[_norm] = _a
    _TOKEN_INDEX.append((_tokens(_q), _a))

_DYNAMIC_NORM: dict[str, str] = {}
_BLACKLIST: set[str] = set()

def _load_cache() -> None:
    if not CACHE_FILE.exists():
        return
    try:
        data = json.loads(CACHE_FILE.read_text(encoding="utf-8"))
        if isinstance(data, dict) and data.get("version") == 2:
            for norm, answer in data.get("dynamic", {}).items():
                if norm not in _NORM_TO_ANSWER:
                    _DYNAMIC_NORM[norm] = answer
            for norm in data.get("blacklist", []):
                _BLACKLIST.add(norm)
        else:
            for norm, answer in data.items():
                if norm not in _NORM_TO_ANSWER:
                    _DYNAMIC_NORM[norm] = answer
        log.info(
            "Кеш загружен: %d динамических, %d в блэклисте",
            len(_DYNAMIC_NORM), len(_BLACKLIST),
        )
    except Exception as e:
        log.warning("Не удалось загрузить кеш: %s", e)

def _save_cache() -> None:
    try:
        data = {
            "version": 2,
            "dynamic": _DYNAMIC_NORM,
            "blacklist": sorted(_BLACKLIST),
        }
        CACHE_FILE.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    except Exception as e:
        log.warning("Не удалось сохранить кеш: %s", e)

_load_cache()

def add_to_dynamic_cache(question: str, answer: str) -> None:
    norm = _normalize(question)
    if not norm or norm in _NORM_TO_ANSWER or norm in _DYNAMIC_NORM:
        return
    _DYNAMIC_NORM[norm] = answer
    _save_cache()

def quarantine_answer(question: str, answer: str, source: str) -> None:
    norm = _normalize(question)
    _BLACKLIST.add(norm)
    _DYNAMIC_NORM.pop(norm, None)
    _save_cache()

    try:
        record = {
            "ts": datetime.now().isoformat(timespec="seconds"),
            "source": source,
            "question": question,
            "answer": answer,
        }
        with QUARANTINE_FILE.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False) + "\n")
    except Exception as e:
        log.warning("Не удалось записать в карантин: %s", e)

def lookup(question: str) -> tuple[str | None, str]:
    norm = _normalize(question)
    if not norm:
        return None, "rag"

    if norm in _BLACKLIST:
        return None, "rag"

    if norm in _NORM_TO_ANSWER:
        return _NORM_TO_ANSWER[norm], "hash"

    if norm in _DYNAMIC_NORM:
        return _DYNAMIC_NORM[norm], "dynamic"

    q_tokens = _tokens(question)
    if not q_tokens:
        return None, "rag"

    best_score = 0.0
    best_answer = None
    for faq_tokens, answer in _TOKEN_INDEX:
        intersection = len(q_tokens & faq_tokens)
        union = len(q_tokens | faq_tokens)
        if union == 0:
            continue
        score = intersection / union
        if score > best_score:
            best_score = score
            best_answer = answer

    if best_score >= FAQ_SIMILARITY_THRESHOLD:
        return best_answer, "fuzzy"

    return None, "rag"

def get_cache_stats() -> dict:
    return {
        "dynamic_count": len(_DYNAMIC_NORM),
        "blacklist_count": len(_BLACKLIST),
    }
