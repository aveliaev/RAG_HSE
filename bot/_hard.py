def sources(query, k=K):
    return [c["source"] for c in RE.retrieve_k(query, k=k, skip_llm_rewrite=True)]

def multi_sources(queries, k=4):
    seen = []
    for q in queries:
        for s in sources(q, k=k):
            seen.append(s)
    return seen

ok_base = 0
for i, c in enumerate(CASES, 1):
    base = sources(c["q"])
    base_set = set(base)
    need = c["need"]
    missing = need - base_set
    verdict = "OK " if not missing else "MISS"
    if not missing and not c.get("expect_miss"):
        ok_base += 1
    print(f"\n[{i}] {verdict}  {c['q'][:78]}")
    print(f"     нужно: {sorted(need) if need else '— (нет в базе)'}")
    print(f"     base top-{K}: {base}")
    if missing:
        print(f"     ❌ НЕ достал: {sorted(missing)}")
        if c.get("decomp"):
            cats = _category_queries(c["q"])
            md = multi_sources(c["decomp"] + cats)
            rec = need - set(md)
            tag = "✅ recovery" if not rec else f"⚠️ всё ещё нет: {sorted(rec)}"
            print(f"     мультизапрос (agentic-имитация): {tag}")
            print(f"        источники: {md}")

print(f"\n==== БАЗОВЫЙ РЕТРИВ: полностью покрыл {ok_base}/{sum(1 for c in CASES if not c.get('expect_miss'))} составных кейсов ====")
